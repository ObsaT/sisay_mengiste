export function SocialIcon({ name, className = "h-4 w-4" }: SocialIconProps) {
  const normalized = name.trim().toLowerCase();

  if (normalized.includes("face")) {
    return <Facebook className={className} />;
  }
  if (normalized.includes("tele") || normalized.includes("tg")) {
    return <TelegramIcon className={className} />;
  }
  if (normalized === "x" || normalized.includes("twit")) {
    return <XIcon className={className} />;
  }
  if (normalized.includes("you") || normalized.includes("yt")) {
    return <Youtube className={className} />;
  }
  if (normalized.includes("tik")) {
    return <TikTokIcon className={className} />;
  }
  if (normalized.includes("link")) {
    return <Linkedin className={className} />;
  }
  if (normalized.includes("insta") || normalized.includes("ig")) {
    return <Instagram className={className} />;
  }
  if (normalized.includes("what") || normalized.includes("wa")) {
    return <WhatsAppIcon className={className} />;
  }

  return <Globe className={className} />;
}
